"""Per-file profiling of historical data (PRD 5.3) and the ``reports/data_profile.md`` writer."""

from dataclasses import asdict, dataclass
from datetime import datetime
from pathlib import Path

import pandas as pd


@dataclass
class FileProfile:
    """Profile of one historical CSV after canonical loading.

    ``pct_missing`` is the share of expected station-snapshots absent, where expected =
    stations x (span / median per-station interval + 1).
    """

    file_name: str
    format: str
    rows: int
    min_ts: datetime | None
    max_ts: datetime | None
    stations: int | None
    median_interval_s: int | None
    pct_missing: float | None
    is_empty: bool
    snapshot_grid_s: int | None = None
    rows_dropped_bad_time: int = 0
    rows_dropped_negative: int = 0
    rows_duplicate: int = 0
    rows_not_renting: int = 0
    rows_over_capacity: int = 0

    def db_row(self, checked_at: datetime) -> dict[str, object]:
        """Columns of ``data_quality_files``.

        Args:
            checked_at: Profiling time.

        Returns:
            Row dict.
        """
        keys = (
            "file_name", "format", "rows", "min_ts", "max_ts", "stations",
            "median_interval_s", "pct_missing", "is_empty",
        )  # fmt: skip
        row: dict[str, object] = {k: asdict(self)[k] for k in keys}
        row["checked_at"] = checked_at
        return row


def _median_seconds(diffs: pd.Series) -> int | None:
    seconds = diffs.dropna().dt.total_seconds()
    return int(seconds.median()) if len(seconds) else None


def profile_frame(file_name: str, fmt: str, df: pd.DataFrame) -> FileProfile:
    """Profile a cleaned canonical frame.

    Args:
        file_name: Source file name.
        fmt: ``"hist_a"`` or ``"hist_b"``.
        df: Canonical rows (after dropping bad times/negatives and duplicates).

    Returns:
        The file profile.
    """
    if df.empty:
        return FileProfile(file_name, fmt, 0, None, None, 0, None, None, True)
    ordered = df.sort_values(["source_id", "observed_at"])
    per_station = _median_seconds(ordered.groupby("source_id")["observed_at"].diff())
    grid = _median_seconds(pd.Series(df["observed_at"].drop_duplicates().sort_values()).diff())
    min_ts, max_ts = df["observed_at"].min(), df["observed_at"].max()
    stations = int(df["source_id"].nunique())
    pct_missing = None
    if per_station:
        expected = stations * ((max_ts - min_ts).total_seconds() / per_station + 1)
        pct_missing = round(max(0.0, 100 * (1 - len(df) / expected)), 2)
    return FileProfile(
        file_name=file_name,
        format=fmt,
        rows=len(df),
        min_ts=min_ts.to_pydatetime(),
        max_ts=max_ts.to_pydatetime(),
        stations=stations,
        median_interval_s=per_station,
        pct_missing=pct_missing,
        is_empty=False,
        snapshot_grid_s=grid,
        rows_not_renting=int((df["is_renting"] == False).sum()),  # noqa: E712
        rows_over_capacity=int(
            (df["bikes_available"] + df["docks_available"] > df["capacity"] + 2).sum()
        ),
    )


def _fmt_ts(value: datetime | None) -> str:
    return value.strftime("%Y-%m-%d %H:%M") if value else "—"


def _fmt(value: object) -> str:
    return "—" if value is None else str(value)


def render_report(
    profiles: list[FileProfile],
    out_of_scope: list[str],
    reconciliation: list[str],
    generated_at: datetime,
) -> str:
    """Render ``reports/data_profile.md``.

    Args:
        profiles: One per in-scope file.
        out_of_scope: Names of listed CSVs not loaded.
        reconciliation: Station reconciliation summary lines.
        generated_at: Report time (UTC).

    Returns:
        Markdown text.
    """
    lines = [
        "# Historical data profile",
        "",
        f"Generated by `dockcast.ingest.historical.backfill` at {generated_at:%Y-%m-%d %H:%M} UTC.",
        "Source: Dublin City Council / Smart Dublin, data.gov.ie `dublinbikes-api` (CC BY 4.0).",
        "All timestamps UTC. `interval` = median per-station gap between observations; `grid` =",
        "median gap between distinct snapshot times; `missing %` = expected station-snapshots",
        "absent (stations x span / interval). Row counts are after dropping unparseable times,",
        "negative counts and duplicate (station, time) rows.",
        "",
        "| file | fmt | rows | from | to | stations | interval s | grid s | missing % "
        "| dup | bad time | negative | not renting | over cap |",
        "|---|---|---:|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for p in sorted(profiles, key=lambda p: (p.min_ts is None, p.min_ts or generated_at)):
        lines.append(
            f"| {p.file_name} | {p.format} | {p.rows} | {_fmt_ts(p.min_ts)} | {_fmt_ts(p.max_ts)} "
            f"| {_fmt(p.stations)} | {_fmt(p.median_interval_s)} | {_fmt(p.snapshot_grid_s)} "
            f"| {_fmt(p.pct_missing)} | {p.rows_duplicate} | {p.rows_dropped_bad_time} "
            f"| {p.rows_dropped_negative} | {p.rows_not_renting} | {p.rows_over_capacity} |"
        )
    total = sum(p.rows for p in profiles)
    empty = [p.file_name for p in profiles if p.is_empty]
    lines += [
        "",
        f"Files: {len(profiles)} loaded, {len(empty)} empty, total rows {total}.",
        "",
        "## Station reconciliation",
        "",
        *[f"- {line}" for line in reconciliation],
        "",
        "## Listed but not loaded (outside PRD 5.3 scope)",
        "",
        *[f"- {name}" for name in out_of_scope],
        "",
    ]
    return "\n".join(lines)


def write_report(text: str, path: Path) -> None:
    """Write the report, creating the directory if needed.

    Args:
        text: Markdown.
        path: Destination.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
