"""Network-wide data gaps (PRD 9.8): detection, storage and ``reports/data_gaps.md``."""

from collections.abc import Sequence
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from pathlib import Path

import pandas as pd
from sqlalchemy import Engine, delete, text
from sqlalchemy.orm import Session

from dockcast.config import PROJECT_ROOT
from dockcast.db.engine import make_engine
from dockcast.db.models import DataGap

# Longest silence that is still normal for each source (PRD 9.8).
GAP_THRESHOLDS = {
    "hist_a": timedelta(minutes=60),
    "hist_b": timedelta(minutes=30),
    "live": timedelta(minutes=30),
}


@dataclass(frozen=True)
class Gap:
    """No observation from any station strictly between ``start`` and ``end``."""

    start: datetime  # last observation before the gap
    end: datetime  # first observation after the gap
    source_before: str
    source_after: str

    @property
    def duration(self) -> timedelta:
        """Length of the gap."""
        return self.end - self.start


def find_gaps(snapshots: pd.DataFrame) -> list[Gap]:
    """Find gaps between consecutive snapshot times.

    A gap exists when the silence exceeds the larger threshold of the two sources around it.

    Args:
        snapshots: One row per distinct ``observed_at`` (UTC) with its ``source``.

    Returns:
        Gaps in chronological order.
    """
    ordered = snapshots.sort_values("observed_at").reset_index(drop=True)
    threshold = ordered["source"].map(GAP_THRESHOLDS)
    frame = pd.DataFrame(
        {
            "start": ordered["observed_at"].shift(),
            "end": ordered["observed_at"],
            "source_before": ordered["source"].shift(),
            "source_after": ordered["source"],
            "limit": pd.concat([threshold.shift(), threshold], axis=1).max(axis=1),
        }
    ).iloc[1:]
    hits = frame[frame["end"] - frame["start"] > frame["limit"]]
    return [
        Gap(
            pd.Timestamp(start).to_pydatetime(),
            pd.Timestamp(end).to_pydatetime(),
            str(before),
            str(after),
        )
        for start, end, before, after in zip(
            hits["start"], hits["end"], hits["source_before"], hits["source_after"], strict=True
        )
    ]


def load_snapshots(engine: Engine) -> pd.DataFrame:
    """Distinct observation times and their source from ``station_status_raw``.

    Args:
        engine: Database engine.

    Returns:
        Columns ``observed_at`` (UTC) and ``source``.
    """
    query = text(
        "SELECT observed_at, min(source) AS source FROM station_status_raw "
        "GROUP BY observed_at ORDER BY observed_at"
    )
    with engine.connect() as conn:
        frame = pd.read_sql(query, conn)
    frame["observed_at"] = pd.to_datetime(frame["observed_at"], utc=True)
    return frame


def load_gaps(session: Session) -> list[Gap]:
    """Read stored gaps.

    Args:
        session: Open session.

    Returns:
        Gaps in chronological order.
    """
    rows = session.query(DataGap).order_by(DataGap.gap_start).all()
    return [Gap(r.gap_start, r.gap_end, r.source_before, r.source_after) for r in rows]


def store_gaps(session: Session, gaps: Sequence[Gap]) -> None:
    """Replace the contents of ``data_gaps``.

    Args:
        session: Open session (caller commits).
        gaps: Gaps to store.
    """
    session.execute(delete(DataGap))
    session.add_all(
        DataGap(
            gap_start=g.start,
            gap_end=g.end,
            source_before=g.source_before,
            source_after=g.source_after,
            duration_s=int(g.duration.total_seconds()),
        )
        for g in gaps
    )


def _fmt_duration(delta: timedelta) -> str:
    days, rest = divmod(int(delta.total_seconds()), 86400)
    hours, rest = divmod(rest, 3600)
    minutes = rest // 60
    return f"{days}d {hours:02d}h {minutes:02d}m" if days else f"{hours}h {minutes:02d}m"


def render_gap_report(gaps: Sequence[Gap], generated_at: datetime) -> str:
    """Render ``reports/data_gaps.md``.

    Args:
        gaps: Detected gaps.
        generated_at: Report time (UTC).

    Returns:
        Markdown text.
    """
    lines = [
        "# Data gaps",
        "",
        f"Generated by `dockcast.quality.gaps` at {generated_at:%Y-%m-%d %H:%M} UTC from "
        "`station_status_raw`.",
        "A gap is a network-wide silence longer than 60 min (Format A) or 30 min (Format B, live);",
        "start = last observation before, end = first observation after (UTC). PRD 9.8.",
        "",
        "| # | start (UTC) | end (UTC) | duration | before | after |",
        "|---:|---|---|---|---|---|",
    ]
    for i, g in enumerate(gaps, 1):
        lines.append(
            f"| {i} | {g.start:%Y-%m-%d %H:%M} | {g.end:%Y-%m-%d %H:%M} "
            f"| {_fmt_duration(g.duration)} | {g.source_before} | {g.source_after} |"
        )
    total = sum((g.duration for g in gaps), timedelta())
    lines += ["", f"{len(gaps)} gaps, total {_fmt_duration(total)}.", ""]
    return "\n".join(lines)


def refresh_gaps(
    engine: Engine, report_path: Path = PROJECT_ROOT / "reports" / "data_gaps.md"
) -> list[Gap]:
    """Recompute gaps from the raw table, store them and write the report.

    Args:
        engine: Database engine.
        report_path: Markdown destination.

    Returns:
        The detected gaps.
    """
    gaps = find_gaps(load_snapshots(engine))
    with Session(engine) as session:
        store_gaps(session, gaps)
        session.commit()
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(render_gap_report(gaps, datetime.now(UTC)), encoding="utf-8")
    return gaps


if __name__ == "__main__":
    refresh_gaps(make_engine())
